create table if not exists public.profiles (
    phone text primary key,
    name text not null,
    created_at timestamptz not null default now()
);

alter table public.profiles add column if not exists is_active boolean not null default true;

create table if not exists public.otp_codes (
    phone text primary key,
    code text not null,
    expires_at timestamptz not null,
    attempts integer not null default 0 check (attempts >= 0)
);

create table if not exists public.sessions (
    token text primary key,
    phone text not null references public.profiles(phone) on delete cascade,
    expires_at timestamptz not null
);

create table if not exists public.products (
    id bigint generated by default as identity primary key,
    sku text not null unique,
    category text not null,
    apple_type text,
    condition text not null,
    brand text not null,
    model text not null,
    taille text,
    seller_price numeric(12, 2) not null,
    final_price numeric(12, 2) not null,
    original_price numeric(12, 2),
    discount numeric(5, 2) not null default 0,
    seller_name text not null,
    seller_phone text not null,
    status text not null default 'APPROVED',
    images jsonb not null default '[]'::jsonb,
    iphone_details jsonb,
    ipad_details jsonb,
    repair_info jsonb,
    created_at date not null default current_date
);

alter table public.products add column if not exists base_price numeric(12, 2);
alter table public.products add column if not exists promotion_enabled boolean not null default false;
alter table public.products add column if not exists promotion_type text;
alter table public.products add column if not exists promotion_value numeric(12, 2);
alter table public.products add column if not exists promotion_starts_at timestamptz;
alter table public.products add column if not exists promotion_ends_at timestamptz;
alter table public.products add column if not exists flash_sale boolean not null default false;
alter table public.products drop constraint if exists products_promotion_type_check;
alter table public.products add constraint products_promotion_type_check check (promotion_type is null or promotion_type in ('percentage', 'fixed'));
alter table public.products drop constraint if exists products_promotion_value_check;
alter table public.products add constraint products_promotion_value_check check (promotion_value is null or promotion_value > 0);

create table if not exists public.offers (
    id text primary key,
    product_id bigint references public.products(id) on delete set null,
    sku text not null,
    product_label text not null,
    product_url text,
    listed_price numeric(12, 2) not null,
    seller_phone text not null,
    buyer_phone text not null,
    buyer_name text not null,
    status text not null,
    history jsonb not null default '[]'::jsonb,
    final_agreed_price numeric(12, 2),
    updated_at timestamptz not null default now()
);

alter table public.offers add column if not exists product_url text;

create table if not exists public.reviews (
    id bigint generated by default as identity primary key,
    order_id text,
    name text not null,
    phone text not null,
    city text,
    rating integer not null check (rating between 1 and 5),
    text text not null,
    avatar text,
    date date not null default current_date
);

create table if not exists public.orders (
    order_id text primary key,
    date date not null default current_date,
    client_name text not null,
    client_phone text not null,
    address text not null,
    items jsonb not null default '[]'::jsonb,
    total_amount numeric(12, 2) not null,
    payment_method text not null,
    status text not null,
    from_offer text,
    seller_payout numeric(12, 2),
    fastwo_commission numeric(12, 2)
);

alter table public.orders add column if not exists city text;
alter table public.orders add column if not exists region text;
alter table public.orders add column if not exists delivery_notes text;
alter table public.orders add column if not exists delivery_status text not null default 'À préparer';

create table if not exists public.whatsapp_conversations (
    id uuid primary key default gen_random_uuid(),
    whatsapp_id text not null unique,
    profile jsonb not null default '{}'::jsonb,
    status text not null default 'active' check (status in ('active', 'waiting_for_customer', 'waiting_for_admin', 'completed')),
    control_mode text not null default 'ai' check (control_mode in ('ai', 'human')),
    draft jsonb not null default '{}'::jsonb,
    order_id text references public.orders(order_id) on delete set null,
    last_message_at timestamptz not null default now(),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.whatsapp_messages (
    id bigint generated by default as identity primary key,
    conversation_id uuid not null references public.whatsapp_conversations(id) on delete cascade,
    whatsapp_message_id text unique,
    direction text not null check (direction in ('inbound', 'outbound')),
    sender_type text not null check (sender_type in ('customer', 'assistant', 'admin', 'system')),
    body text not null,
    payload jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

create index if not exists whatsapp_conversations_status_idx on public.whatsapp_conversations(status, last_message_at desc);
create index if not exists whatsapp_messages_conversation_idx on public.whatsapp_messages(conversation_id, created_at);

create table if not exists public.delivery_fees (
    id bigint generated by default as identity primary key,
    name text not null unique,
    amount numeric(12, 2) not null check (amount >= 0),
    minimum_order numeric(12, 2) not null default 0 check (minimum_order >= 0),
    maximum_order numeric(12, 2),
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

